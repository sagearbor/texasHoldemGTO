"""Dev helper: crop rough index boxes (thumb coords x4) into a contact sheet."""
import sys, cv2, numpy as np
D = 'camera_data/cards-2deals_TH/'
B = [
 ('052737969','Qc',(18,380,70,490)),('052737969','5d',(195,435,258,535)),('052737969','5d_b',(290,825,352,925)),
 ('052745925','Qc',(178,508,215,585)),('052745925','5d',(310,530,345,605)),('052745925','5d_b',(410,765,450,825)),
 ('052754698','Qc',(135,578,175,645)),('052754698','5d',(280,640,335,690)),
 ('052809072','6h',(110,490,165,560)),('052809072','Ac',(250,580,340,615)),
 ('052824832','6h',(75,610,110,685)),('052824832','Ac',(180,610,225,680)),('052824832','Ac_b',(255,865,305,930)),
 ('052831500','6h',(90,690,140,745)),('052831500','Ac',(300,685,370,725)),('052831500','Ac_b',(320,855,375,890)),
 ('052836314','6h',(140,725,190,780)),('052836314','Ac',(295,662,335,725)),('052836314','Ac_b',(425,870,465,930)),
]
tiles=[]
cache={}
for p,c,(x0,y0,x1,y1) in B:
    if p not in cache: cache[p]=cv2.imread(D+'PXL_20261027_'+p+'.jpg')
    im=cache[p]; m=10
    cr=im[(y0-m)*4:(y1+m)*4,(x0-m)*4:(x1+m)*4]
    s=300/max(cr.shape[:2]); cr=cv2.resize(cr,None,fx=s,fy=s)
    t=np.full((320,320,3),255,np.uint8); t[:cr.shape[0],:cr.shape[1]]=cr
    cv2.putText(t,p[-3:]+' '+c,(5,315),0,0.6,(0,0,255),2); tiles.append(t)
while len(tiles)%5: tiles.append(np.full((320,320,3),128,np.uint8))
rows=[np.hstack(tiles[i:i+5]) for i in range(0,len(tiles),5)]
cv2.imwrite(sys.argv[1],np.vstack(rows))
